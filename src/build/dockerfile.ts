/**
 * The generated Dockerfile and build context of the app image. The Meteor bundle is split in two:
 * the inputs of `npm install` are copied first, the rest of the app after `npm install`. Docker's
 * layer cache then reuses the expensive `npm install` layer whenever only app code changed, and a
 * server that already has the old image pulls only the small app layers.
 */
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { lstat, readdir, readFile, readlink } from 'node:fs/promises';
import { basename, join, normalize, posix } from 'node:path';

/**
 * Bumped whenever the generated Dockerfile changes shape. It is part of the build cache key, so
 * images built with an older layout are not reused.
 */
export const DOCKERFILE_VERSION = 2;

/**
 * Meteor writes `.meteor-portable-2.json` build-tool caches into the app's node_modules during a
 * build, so the next bundle contains them while the first one after a fresh `npm install` does
 * not. They are not used at runtime, but they would change the deps layer and rebuild the
 * `npm install` layer (which every server then pulls again) for a code-only change. The regex
 * (used for `computeDepsHash`) and the `.dockerignore` pattern must exclude the same files.
 */
const IGNORED_CONTEXT_FILE_RE = /^\.meteor-portable.*\.json$/;
const CONTEXT_IGNORE = ['**/.meteor-portable*.json'];

/**
 * Writes the `.dockerignore` of the build context (overwriting an existing one). The Dockerfile
 * comes from stdin (`-f -`), so Docker reads the ignore file from the context root. It has the
 * same exclusions as `computeDepsHash`, so the hash and the deps layer see the same files.
 */
export function writeContextIgnore(contextDir: string): void {
  writeFileSync(join(contextDir, '.dockerignore'), `# Generated by comet-deploy\n${CONTEXT_IGNORE.join('\n')}\n`);
}

/**
 * What `npm install` in `programs/server` always reads when present: the manifests, `npm/` (the
 * npm packages of the app and of Meteor packages) and Meteor's install script `npm-rebuild.js`,
 * which rebuilds the native modules listed in `npm-rebuilds.json` for the image's platform.
 */
const BASE_DEPS = ['package.json', 'npm-shrinkwrap.json', 'package-lock.json', 'npm-rebuild.js', 'npm-rebuilds.json', 'npm'];
/** `require("./…")` of a local file; only `./` paths are followed. */
const LOCAL_REQUIRE_RE = /require\(\s*["'](\.\/[^"']+)["']\s*\)/g;
/** `node <file>.js` in a package.json script (Meteor's `install` is `node npm-rebuild.js`). */
const SCRIPT_FILE_RE = /\bnode\s+([\w./-]+\.js)\b/g;

/**
 * Files in `programs/server` that `npm install` (and its `node npm-rebuild.js` install script)
 * reads: manifests, `npm/`, the scripts named in package.json and, transitively, every local file
 * they `require("./…")`. Paths are relative to `serverDir`, sorted, and only existing ones.
 */
export function detectDepsFiles(serverDir: string): string[] {
  const found = new Set<string>();
  const queue: string[] = [];
  const add = (rel: string) => {
    const r = normalize(rel).replace(/^\.\//, '');
    if (found.has(r) || !existsSync(join(serverDir, r))) return;
    found.add(r);
    if (r.endsWith('.js')) queue.push(r);
  };
  for (const f of BASE_DEPS) add(f);
  try {
    const scripts = JSON.parse(readFileSync(join(serverDir, 'package.json'), 'utf8')).scripts ?? {};
    for (const cmd of Object.values(scripts)) for (const m of String(cmd).matchAll(SCRIPT_FILE_RE)) add(m[1]);
  } catch {
    // no or invalid package.json: nothing to add
  }
  while (queue.length) {
    const file = queue.shift()!;
    if (!statSync(join(serverDir, file)).isFile()) continue;
    for (const m of readFileSync(join(serverDir, file), 'utf8').matchAll(LOCAL_REQUIRE_RE)) add(posix.join(posix.dirname(file), m[1]));
  }
  return [...found].sort();
}

/** Which parts of the bundle go into which `COPY` of the generated Dockerfile. */
export interface BuildContextPlan {
  /** Context-relative paths of the dependency inputs (programs/server). */
  depsCopy: string[];
  /** Everything else: context-relative source → absolute destination in the image. */
  appCopy: Array<{ from: string; to: string }>;
}

/**
 * Splits the bundle into the deps inputs and the app. The build context is the parent of
 * `bundleDir` (the build location), so every source starts with `bundle/`.
 *
 * The app is copied entry by entry (the top level of `bundle/`, `bundle/programs` and
 * `bundle/programs/server`) instead of with one `COPY bundle /built_app`, which would copy
 * `programs/server/npm` (often hundreds of MB) a second time into a later layer. Entries are
 * sorted so the same bundle always gives the same Dockerfile.
 */
export function planBuildContext(bundleDir: string): BuildContextPlan {
  const serverDir = join(bundleDir, 'programs/server');
  const deps = detectDepsFiles(serverDir);
  const appCopy: Array<{ from: string; to: string }> = [];
  const entries = (dir: string) => (existsSync(dir) ? readdirSync(dir).sort() : []);
  for (const e of entries(bundleDir)) {
    if (e !== 'programs') appCopy.push({ from: `bundle/${e}`, to: `/built_app/${e}` });
  }
  for (const e of entries(join(bundleDir, 'programs'))) {
    if (e !== 'server') appCopy.push({ from: `bundle/programs/${e}`, to: `/built_app/programs/${e}` });
  }
  // A nested deps file (`lib/x.js`) does not match a top-level entry, so its directory is copied
  // with the app as well; the duplicate has the same content.
  for (const e of entries(serverDir)) {
    if (!deps.includes(e)) appCopy.push({ from: `bundle/programs/server/${e}`, to: `/built_app/programs/server/${e}` });
  }
  return { depsCopy: deps.map((f) => `bundle/programs/server/${f}`), appCopy };
}

/**
 * Renders the Dockerfile, which `docker buildx build -f -` reads from stdin. In order: `FROM`,
 * MUP's `mkdir /built_app`, one `ARG` per `argKeys`, the user's `buildInstructions` (MUP applies
 * them only when it builds on the server; comet-deploy always does), the deps inputs,
 * `npm install`, then the rest of the app.
 *
 * BuildKit keys a `COPY` by the content of its files, not their mtime, so as long as the deps
 * inputs are byte-identical the `npm install` layer is a cache hit even though `meteor build`
 * wrote them fresh, and a code-only change rebuilds (and ships) only the app `COPY` layers.
 *
 * No env values are baked in: only `argKeys` (env keys that build instructions reference) become
 * ARGs, with their values passed as `--build-arg`. `NODE_VERSION` is not declared here because the
 * base image consumes it in its own `ONBUILD` instructions.
 *
 * `chownApp` copies the files as `app:app`, so `npm install` can run as the `app` user of the
 * zodern/meteor images.
 */
export function renderDockerfile(o: {
  baseImage: string;
  buildInstructions: string[];
  argKeys: string[];
  plan: BuildContextPlan;
  chownApp: boolean;
}): string {
  const chown = o.chownApp ? '--chown=app:app ' : '';
  // A directory listed in a multi-source COPY is copied by its contents, and files land in the
  // destination by their basename, so `npm/` gets its own COPY with an explicit destination.
  // A nested file (`lib/x.js`) would land as `programs/server/x.js` that way too, so it gets its
  // own COPY to its full path.
  const npmDir = o.plan.depsCopy.find((p) => p.endsWith('/programs/server/npm'));
  const inServer = (p: string) => posix.relative('bundle/programs/server', p);
  const depFiles = o.plan.depsCopy.filter((p) => p !== npmDir && !inServer(p).includes('/'));
  const nestedDepFiles = o.plan.depsCopy.filter((p) => p !== npmDir && inServer(p).includes('/'));
  const lines = [
    `# Generated by comet-deploy (Dockerfile v${DOCKERFILE_VERSION})`,
    `FROM ${o.baseImage}`,
    'RUN mkdir /built_app || true',
    ...o.argKeys.map((k) => `ARG ${k}`),
    ...o.buildInstructions,
  ];
  if (depFiles.length) lines.push(`COPY ${chown}${depFiles.join(' ')} /built_app/programs/server/`);
  for (const p of nestedDepFiles) lines.push(`COPY ${chown}${p} /built_app/programs/server/${inServer(p)}`);
  if (npmDir) lines.push(`COPY ${chown}${npmDir} /built_app/programs/server/npm`);
  // Same command as MUP. `--unsafe-perm` keeps npm 6 (older Meteor releases) from running the
  // install scripts as `nobody` when it runs as root.
  lines.push('RUN cd /built_app/programs/server && npm install --unsafe-perm');
  for (const c of o.plan.appCopy) lines.push(`COPY ${chown}${c.from} ${c.to}`);
  return lines.join('\n') + '\n';
}

/**
 * Env keys (from `app.env`) that build instructions reference as `$KEY` or `${KEY}`, sorted.
 * `$KEY` counts only as a whole name (`$KEY_2` does not reference `KEY`). Only these keys become
 * ARGs, so other env values, which are often secrets, never reach the image or its history.
 */
export function argKeysForInstructions(instructions: string[], envKeys: string[]): string[] {
  const text = instructions.join('\n');
  // MUP's schema allows any env key name, so the key is escaped before it goes into the pattern.
  const literal = (k: string) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return envKeys.filter((k) => new RegExp(`\\$(\\{${literal(k)}\\}|${literal(k)}(?![A-Za-z0-9_]))`).test(text)).sort();
}

/**
 * Appends `rel` (a file) or every file below it (a directory) to `out` as context-relative
 * paths, in sorted order, skipping Meteor's portable markers like the `.dockerignore` does.
 */
async function listTree(root: string, rel: string, out: string[]): Promise<void> {
  const abs = join(root, rel);
  // lstat: a symlink is listed as itself (COPY copies it as a link), never followed, so a
  // dangling link or a link cycle under npm/ cannot break or loop the walk.
  const st = lstatSync(abs);
  if (!st.isDirectory()) {
    if (!IGNORED_CONTEXT_FILE_RE.test(basename(rel))) out.push(rel);
    return;
  }
  for (const e of (await readdir(abs)).sort()) await listTree(root, posix.join(rel, e), out);
}

/**
 * Content hash of the deps inputs: sha256 over the relative path and content of every file
 * (mtime-independent). Unlike BuildKit's own cache it does not depend on the machine that builds,
 * so it can later identify a shared deps image (for example for CI). It is stored as the image
 * label `comet-deploy.deps-hash` and in the build cache.
 */
export async function computeDepsHash(bundleDir: string, plan: BuildContextPlan): Promise<string> {
  const contextDir = join(bundleDir, '..');
  const files: string[] = [];
  for (const p of plan.depsCopy) await listTree(contextDir, p, files);
  files.sort();
  // `npm/` can hold tens of thousands of files: hash them with 16 concurrent readers. Taking
  // `next++` is synchronous, so no two workers get the same index.
  const digests = new Array<string>(files.length);
  let next = 0;
  const worker = async () => {
    while (next < files.length) {
      const i = next++;
      const abs = join(contextDir, files[i]);
      const content = (await lstat(abs)).isSymbolicLink() ? `symlink:${await readlink(abs)}` : await readFile(abs);
      digests[i] = createHash('sha256').update(content).digest('hex');
    }
  };
  await Promise.all(Array.from({ length: 16 }, worker));
  const h = createHash('sha256');
  files.forEach((f, i) => h.update(`${f}\0${digests[i]}\n`));
  return h.digest('hex');
}
